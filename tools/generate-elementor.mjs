/**
 * Prepares the Elementor plugin from the build output:
 *
 *   dist/manifest.json  ->  adapters/elementor/includes/generated/schemas.php
 *   dist/aurora*.min.js ->  adapters/elementor/assets/js/aurora/
 *
 * The plugin generates its Elementor controls from the module schemas, so the
 * schemas are the single source of truth for option names, defaults, ranges
 * and labels.
 */

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

var root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
var dist = resolve(root, 'dist');
var plugin = resolve(root, 'adapters/elementor');

if (!existsSync(resolve(dist, 'manifest.json'))) {
    console.error('dist/manifest.json not found. Run `npm run build` first.');
    process.exit(1);
}

var manifest = JSON.parse(readFileSync(resolve(dist, 'manifest.json'), 'utf8'));

/** Serializes a JSON value as a PHP array literal. */
function toPhp(value, depth) {
    var pad = '\t'.repeat(depth);
    var inner = '\t'.repeat(depth + 1);

    if (value === null) return 'null';
    if (typeof value === 'boolean') return value ? 'true' : 'false';
    if (typeof value === 'number') return String(value);
    if (typeof value === 'string') return "'" + value.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

    if (Array.isArray(value)) {
        if (!value.length) return '[]';
        return '[\n' + value.map((item) => inner + toPhp(item, depth + 1) + ',').join('\n') + '\n' + pad + ']';
    }

    var keys = Object.keys(value);
    if (!keys.length) return '[]';
    return '[\n' + keys.map((key) => inner + toPhp(key, 0) + ' => ' + toPhp(value[key], depth + 1) + ',').join('\n') + '\n' + pad + ']';
}

var header = "<?php\n/**\n * Option schemas of every Aurora module.\n *\n * GENERATED by tools/generate-elementor.mjs from the module schemas.\n * Do not edit by hand.\n */\n\nif ( ! defined( 'ABSPATH' ) ) {\n\texit;\n}\n\nreturn ";

mkdirSync(resolve(plugin, 'includes/generated'), { recursive: true });
writeFileSync(resolve(plugin, 'includes/generated/schemas.php'), header + toPhp(manifest.schemas, 0) + ";\n");

var target = resolve(plugin, 'assets/js/aurora');
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
manifest.files
    .map((f) => f.file)
    .filter((file) => file.endsWith('.min.js'))
    .forEach((file) => copyFileSync(resolve(dist, file), resolve(target, file)));

// The animated-headlines engine ships as its own pair of files: the modules
// built on it (highlight, and the counter and headline work that follows)
// share one copy rather than each bundling the component library.
var engine = resolve(root, 'node_modules/@vianetz/animated-headlines-vanilla/dist');
if (!existsSync(engine)) {
    console.error('animated-headlines is not installed; run npm install first.');
    process.exit(1);
}
var engineTarget = resolve(plugin, 'assets/vendor');
rmSync(engineTarget, { recursive: true, force: true });
mkdirSync(engineTarget, { recursive: true });
['animated-headline.js', 'animated-headline.css'].forEach(function (file) {
    copyFileSync(resolve(engine, file), resolve(engineTarget, file));
});

writeFileSync(resolve(target, 'version.json'), JSON.stringify({ version: manifest.version }) + '\n');
console.log('Elementor plugin prepared with Aurora ' + manifest.version + '.');
